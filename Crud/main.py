import oracledb

DB_USER = "seu_usuario"
DB_PASS = "seu_senha"
# DB_DSN = "seu_host:porta/seu_servico"
DB_DNS = "oracle.fiap.com.br:1521/orcl"

def obter_conexao():
    try:
        conexao = oracledb.connect(user=DB_USER, password=DB_PASS, dsn=DB_DNS)
        return conexao
    except oracledb.Error as e:
        print(f"Erro ao conectar ao banco de dados: {e}")
        return None

def criar_tabela():
    sql ="""
    CREATE TABLE alunos (
        ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        NOME VARCHAR2(100) NOT NULL,
        EMAIL VARCHAR2(100) NOT NULL UNIQUE,
        CURSO VARCHAR2(50) DEFAULT 'ADS'
    )
   """
    
    conexao = obter_conexao()
    if conexao:
        try:
            cursor = conexao.cursor()
            cursor.execute(sql)
            print("Tabela 'alunos' criada com sucesso.")
        except oracledb.Error as e:
            if "ORA-00955" in str(e):
                print("A tabela 'alunos' já existe.")
            else:
                print(f"Erro ao criar a tabela: {e}")
        finally:
            conexao.close()

def criar_aluno(nome, email, curso='ADS'):
    """
    Insere um novo aluno na tabela usando Prepared Statements(:1, :2, :3).
    """
    sql = "INSERT INTO alunos (NOME, EMAIL, CURSO) VALUES (:1, :2, :3)"

    conexao = obter_conexao()
    if conexao:
        try:
            cursor = conexao.cursor()
            cursor.execute(sql, (nome, email, curso))
            conexao.commit()
            print(f"Aluno '{nome}' inserido com sucesso.")
        except oracledb.Error as e:
                print(f"Erro ao inserir aluno: {e}")
        finally:
            conexao.close()   

